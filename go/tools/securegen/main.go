// Command securegen is the build-time code generator for layer 3 (custom string
// encryption). It reads a plaintext manifest (build/secrets.src.json) that is
// NEVER compiled into the program, encrypts every entry with a freshly minted
// per-build key fragment, and emits internal/appsecrets/secrets_gen.go containing
// only ciphertext + the fragment. The plaintext therefore never appears as a
// string literal anywhere in the Go sources that garble compiles.
//
// Run it before every build:
//
//	go run ./tools/securegen
//
// It is wired as a //go:generate directive in internal/appsecrets/doc.go.
package main

import (
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"sort"
	"strings"

	"sentinel/internal/secure/keymix"
)

const (
	manifestPath = "build/secrets.src.json"
	outputPath   = "internal/appsecrets/secrets_gen.go"
)

func main() {
	log.SetFlags(0)
	log.SetPrefix("securegen: ")

	raw, err := os.ReadFile(manifestPath)
	if err != nil {
		log.Fatalf("read manifest: %v", err)
	}
	var manifest map[string]string
	if err := json.Unmarshal(raw, &manifest); err != nil {
		log.Fatalf("parse manifest: %v", err)
	}
	if len(manifest) == 0 {
		log.Fatal("manifest is empty")
	}

	// Fresh per-build fragment so two builds never share a master key.
	fragB := make([]byte, 16)
	if _, err := rand.Read(fragB); err != nil {
		log.Fatalf("rand: %v", err)
	}
	key := keymix.Derive(fragB)
	block, err := aes.NewCipher(key[:])
	if err != nil {
		log.Fatalf("cipher: %v", err)
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		log.Fatalf("gcm: %v", err)
	}

	names := make([]string, 0, len(manifest))
	for k := range manifest {
		names = append(names, k)
	}
	sort.Strings(names)

	var body bytes.Buffer
	for _, name := range names {
		blob, err := seal(gcm, manifest[name])
		if err != nil {
			log.Fatalf("seal %s: %v", name, err)
		}
		fmt.Fprintf(&body, "\t%s = Secret{%q}\n", goIdent(name), blob)
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, header, fragBytes(fragB), body.String())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatalf("gofmt generated source: %v\n%s", err, out.String())
	}
	if err := os.WriteFile(outputPath, formatted, 0o644); err != nil {
		log.Fatalf("write output: %v", err)
	}
	log.Printf("wrote %s (%d secrets)", outputPath, len(manifest))
}

func seal(gcm cipher.AEAD, plaintext string) (string, error) {
	nonce := make([]byte, gcm.NonceSize())
	if _, err := io.ReadFull(rand.Reader, nonce); err != nil {
		return "", err
	}
	ct := gcm.Seal(nil, nonce, []byte(plaintext), nil)
	return base64.StdEncoding.EncodeToString(append(nonce, ct...)), nil
}

func fragBytes(b []byte) string {
	var sb strings.Builder
	for i, v := range b {
		if i > 0 {
			sb.WriteString(", ")
		}
		fmt.Fprintf(&sb, "0x%02x", v)
	}
	return sb.String()
}

// goIdent turns an UPPER_SNAKE manifest key into an exported CamelCase Go ident.
func goIdent(k string) string {
	parts := strings.FieldsFunc(k, func(r rune) bool { return r == '_' || r == '-' || r == '.' || r == ' ' })
	var sb strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		sb.WriteString(strings.ToUpper(p[:1]))
		sb.WriteString(strings.ToLower(p[1:]))
	}
	id := sb.String()
	if id == "" {
		id = "Secret"
	}
	return id
}

const header = `// Code generated by tools/securegen. DO NOT EDIT.
// The plaintext source lives in build/secrets.src.json and is never compiled.
package appsecrets

import "sentinel/internal/secure"

// fragB is the per-build key fragment. Regenerated on every run of securegen.
var fragB = []byte{%s}

// Secret is an opaque handle to one AES-GCM encrypted string.
type Secret struct{ blob string }

// Reveal decrypts the secret, hands the plaintext to fn, then wipes it.
// Preferred for anything genuinely sensitive.
func (s Secret) Reveal(fn func([]byte)) error { return secure.With(s.blob, fragB, fn) }

// String decrypts and returns the value as a (non-wipeable) Go string.
// Use only for values that are not secret on their own.
func (s Secret) String() string { return secure.String(s.blob, fragB) }

// Equal reports whether the secret's plaintext equals want, without the
// plaintext escaping as a string. Constant-time within the compared length.
func (s Secret) Equal(want []byte) bool {
	ok := false
	_ = s.Reveal(func(pt []byte) {
		if len(pt) != len(want) {
			return
		}
		var diff byte
		for i := range pt {
			diff |= pt[i] ^ want[i]
		}
		ok = diff == 0
	})
	return ok
}

var (
%s)
`
